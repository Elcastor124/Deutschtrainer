// Iconos dot-matrix (9×9) para los objetos: como una pantalla de puntos.
import type { ItemId } from '../../shared/types.ts';

export const GLYPHS: Record<ItemId, string[]> = {
  blackcard: ['....#....', '...###...', '..#####..', '.#######.', '#########', '#########', '.##.#.##.', '....#....', '...###...'],
  thief: ['.........', '.........', '#########', '##..#..##', '#.##.##.#', '#########', '.##...##.', '.........', '.........'],
  shield: ['#########', '#########', '##.....##', '##.....##', '##.....##', '.##...##.', '..##.##..', '...###...', '....#....'],
  double: ['.........', '#...#.##.', '.#.#.#..#', '..#....#.', '.#.#..#..', '#...#.###', '.........', '.........', '.........'],
  sabotage: ['.....##..', '....##...', '...##....', '..######.', '....##...', '...##....', '..##.....', '.##......', '.#.......'],
  second: ['..#####..', '.##...##.', '.......##', '......##.', '....##...', '..##.....', '.##......', '.#######.', '.........'],
  wildcard: ['....#....', '....#....', '...###...', '#########', '.#######.', '..#####..', '..##.##..', '.##...##.', '.#.....#.'],
};

export function Glyph({ item, color = 'currentColor', dim = 'rgba(242,241,238,0.08)', className }: { item: ItemId; color?: string; dim?: string; className?: string }) {
  const rows = GLYPHS[item];
  return (
    <svg className={className} viewBox="0 0 90 90" aria-hidden="true">
      {rows.flatMap((row, y) =>
        [...row].map((c, x) => <circle key={`${x}-${y}`} cx={x * 10 + 5} cy={y * 10 + 5} r={c === '#' ? 4 : 2} fill={c === '#' ? color : dim} />),
      )}
    </svg>
  );
}
